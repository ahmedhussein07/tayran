-- ---------------------------------------------------------------------------------------------
-- Images: one row per normalized image (by content hash). Files live in object storage under
-- p/{hash}_{w}.webp (products) or c/{hash}_{w}.webp (categories).
-- ---------------------------------------------------------------------------------------------
CREATE TABLE images (
    hash               VARCHAR(12) PRIMARY KEY,
    kind               VARCHAR(16) NOT NULL,
    bg                 VARCHAR(7)  NOT NULL,          -- dominant colour, #RRGGBB
    created_at         TIMESTAMPTZ NOT NULL,
    last_referenced_at TIMESTAMPTZ NOT NULL,
    CONSTRAINT ck_images_kind CHECK (kind IN ('PRODUCT', 'CATEGORY'))
);

