-- Phase 2: admin users, stores, managed catalog (categories, subcategories, products), images.

-- ---------------------------------------------------------------------------------------------
-- Users: a role, and a password for admins only. The same phone may exist once per role, so an
-- admin can also shop as a customer with the same number.
-- ---------------------------------------------------------------------------------------------
ALTER TABLE users
    ADD COLUMN role               VARCHAR(16) NOT NULL DEFAULT 'CUSTOMER',
    ADD COLUMN password_hash      VARCHAR(100),
    ADD COLUMN failed_login_count INT         NOT NULL DEFAULT 0,
    ADD COLUMN locked_until       TIMESTAMPTZ,
    ADD COLUMN active             BOOLEAN     NOT NULL DEFAULT TRUE,
    ADD CONSTRAINT ck_users_role CHECK (role IN ('CUSTOMER', 'ADMIN'));

ALTER TABLE users DROP CONSTRAINT uq_users_phone;
ALTER TABLE users ADD CONSTRAINT uq_users_phone_role UNIQUE (phone, role);

-- ---------------------------------------------------------------------------------------------
-- Stores. One for now; every village belongs to a store, and each store has its own published
-- catalog (prices and availability differ per store).
-- ---------------------------------------------------------------------------------------------
CREATE TABLE stores (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name            VARCHAR(100) NOT NULL,
    catalog_version INT          NOT NULL DEFAULT 0,
    catalog_dirty   BOOLEAN      NOT NULL DEFAULT TRUE
);
