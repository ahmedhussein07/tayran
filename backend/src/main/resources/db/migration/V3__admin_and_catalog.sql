CREATE TABLE subcategories (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category_id BIGINT      NOT NULL REFERENCES categories (id),
    name_ar     VARCHAR(50) NOT NULL,
    name_en     VARCHAR(50) NOT NULL,
    sort_order  INT         NOT NULL DEFAULT 0,
    active      BOOLEAN     NOT NULL DEFAULT TRUE
);
CREATE INDEX idx_subcategories_category ON subcategories (category_id);

CREATE TABLE products (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    subcategory_id  BIGINT       NOT NULL REFERENCES subcategories (id),
    name_ar         VARCHAR(100) NOT NULL,
    name_en         VARCHAR(100) NOT NULL,
    size_label      VARCHAR(40)  NOT NULL,      -- "1 كيلو", "500 جم": Western digits, the app localizes them
    description     VARCHAR(600),
    ingredients     VARCHAR(600),
    image_hash      VARCHAR(12) REFERENCES images (hash),
    image_bg        VARCHAR(7),
    active          BOOLEAN      NOT NULL DEFAULT TRUE,
    sort_order      INT          NOT NULL DEFAULT 0,
    deleted_at      TIMESTAMPTZ,                -- soft delete: future orders keep referencing the row
    created_on      TIMESTAMPTZ  NOT NULL DEFAULT now(),
    last_updated_on TIMESTAMPTZ  NOT NULL DEFAULT now()
);
CREATE INDEX idx_products_subcategory ON products (subcategory_id);

-- Per-store price and availability.
CREATE TABLE store_products (
    store_id   BIGINT        NOT NULL REFERENCES stores (id),
    product_id BIGINT        NOT NULL REFERENCES products (id),
    price      NUMERIC(10, 2) NOT NULL,
    old_price  NUMERIC(10, 2),
    available  BOOLEAN       NOT NULL DEFAULT TRUE,
    PRIMARY KEY (store_id, product_id),
    CONSTRAINT ck_store_products_price CHECK (price >= 0),
    CONSTRAINT ck_store_products_old_price CHECK (old_price IS NULL OR old_price > price)
);

-- Every published catalog file, so old versions can be deleted without listing the bucket.
CREATE TABLE catalog_publications (
    store_id     BIGINT       NOT NULL REFERENCES stores (id),
    version      INT          NOT NULL,
    object_key   VARCHAR(200) NOT NULL,
    published_at TIMESTAMPTZ  NOT NULL,
    deleted_at   TIMESTAMPTZ,
    PRIMARY KEY (store_id, version)
);
