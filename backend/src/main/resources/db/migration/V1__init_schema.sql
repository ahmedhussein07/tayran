-- Phase 1: sign-in / sign-up up to home.

CREATE TABLE users (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    phone           VARCHAR(13) NOT NULL,          -- E.164, +201XXXXXXXXX
    first_name      VARCHAR(30),
    last_name       VARCHAR(30),
    created_on      TIMESTAMPTZ NOT NULL DEFAULT now(),
    last_updated_on TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT uq_users_phone UNIQUE (phone)
);

CREATE TABLE otp_challenges (
    id                  UUID PRIMARY KEY,
    phone               VARCHAR(13) NOT NULL,
    code_hash           VARCHAR(64) NOT NULL,      -- HMAC-SHA256(secret, challengeId:code); the code itself is never stored
    attempts            INT         NOT NULL DEFAULT 0,
    expires_at          TIMESTAMPTZ NOT NULL,
    resend_available_at TIMESTAMPTZ NOT NULL,
    consumed_at         TIMESTAMPTZ,
    superseded_at       TIMESTAMPTZ,                -- set when a newer code is requested for the same phone
    created_on          TIMESTAMPTZ NOT NULL
);
CREATE INDEX idx_otp_challenges_phone_created ON otp_challenges (phone, created_on DESC);

CREATE TABLE refresh_tokens (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id        BIGINT      NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    token_hash     VARCHAR(64) NOT NULL,           -- SHA-256 of the opaque token
    family_id      UUID        NOT NULL,           -- all tokens rotated from one sign-in
    expires_at     TIMESTAMPTZ NOT NULL,
    revoked_at     TIMESTAMPTZ,
    replaced_by_id BIGINT REFERENCES refresh_tokens (id),
    created_on     TIMESTAMPTZ NOT NULL,
    CONSTRAINT uq_refresh_tokens_hash UNIQUE (token_hash)
);
CREATE INDEX idx_refresh_tokens_family ON refresh_tokens (family_id);
CREATE INDEX idx_refresh_tokens_user ON refresh_tokens (user_id);

CREATE TABLE villages (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name_ar    VARCHAR(100) NOT NULL,
    name_en    VARCHAR(100) NOT NULL,
    active     BOOLEAN      NOT NULL DEFAULT TRUE,
    sort_order INT          NOT NULL DEFAULT 0,
    CONSTRAINT uq_villages_name_ar UNIQUE (name_ar)
);

CREATE TABLE streets (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    village_id BIGINT       NOT NULL REFERENCES villages (id),
    name_ar    VARCHAR(100) NOT NULL,
    name_en    VARCHAR(100) NOT NULL,
    active     BOOLEAN      NOT NULL DEFAULT TRUE,
    sort_order INT          NOT NULL DEFAULT 0,
    CONSTRAINT uq_streets_id_village UNIQUE (id, village_id),
    CONSTRAINT uq_streets_village_name_ar UNIQUE (village_id, name_ar)
);

CREATE TABLE addresses (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id         BIGINT       NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    village_id      BIGINT       NOT NULL REFERENCES villages (id),
    street_id       BIGINT       NOT NULL,
    landmark        VARCHAR(150) NOT NULL,
    is_default      BOOLEAN      NOT NULL DEFAULT TRUE,
    created_on      TIMESTAMPTZ  NOT NULL DEFAULT now(),
    last_updated_on TIMESTAMPTZ  NOT NULL DEFAULT now(),
    -- The street must belong to the chosen village, enforced by the database too.
    CONSTRAINT fk_addresses_street_in_village FOREIGN KEY (street_id, village_id) REFERENCES streets (id, village_id)
);
CREATE UNIQUE INDEX uq_addresses_one_default_per_user ON addresses (user_id) WHERE is_default;

CREATE TABLE categories (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name_ar     VARCHAR(50) NOT NULL,
    name_en     VARCHAR(50) NOT NULL,
    icon_key    VARCHAR(30) NOT NULL,              -- maps to the app's bundled category art
    color_token VARCHAR(30) NOT NULL,              -- a pastel token from the design system, e.g. pastel-mint
    sort_order  INT         NOT NULL,
    active      BOOLEAN     NOT NULL DEFAULT TRUE,
    CONSTRAINT uq_categories_icon_key UNIQUE (icon_key)
);
