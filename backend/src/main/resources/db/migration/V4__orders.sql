-- Phase 3: saved addresses, store settings, orders with their items and events, push devices.

-- ---- users ---------------------------------------------------------------------------------

-- Language for push texts (the app's own language is local).
ALTER TABLE users
    ADD COLUMN preferred_language VARCHAR(2) NOT NULL DEFAULT 'ar',
    ADD CONSTRAINT ck_users_language CHECK (preferred_language IN ('ar', 'en'));

-- ---- addresses: many per user, soft delete -------------------------------------------------

ALTER TABLE addresses
    ADD COLUMN label      VARCHAR(30),   -- optional, e.g. البيت / الشغل
    ADD COLUMN deleted_at TIMESTAMPTZ;   -- soft delete: orders keep their own snapshot anyway

DROP INDEX uq_addresses_one_default_per_user;
CREATE UNIQUE INDEX uq_addresses_one_default_per_user ON addresses (user_id) WHERE is_default AND deleted_at IS NULL;
CREATE INDEX ix_addresses_user_live ON addresses (user_id) WHERE deleted_at IS NULL;

-- ---- store settings (one store for now) ----------------------------------------------------

CREATE TABLE store_settings (
    store_id                BIGINT PRIMARY KEY REFERENCES stores (id),
    delivery_fee            NUMERIC(10, 2) NOT NULL CHECK (delivery_fee >= 0),
    free_delivery_threshold NUMERIC(10, 2) NOT NULL CHECK (free_delivery_threshold >= 0),
    min_order_amount        NUMERIC(10, 2) NOT NULL CHECK (min_order_amount >= 0),
    online_payment_fee      NUMERIC(10, 2) NOT NULL CHECK (online_payment_fee >= 0),
    eta_minutes             INT            NOT NULL CHECK (eta_minutes BETWEEN 5 AND 240),
    updated_at              TIMESTAMPTZ    NOT NULL DEFAULT now(),
    updated_by              BIGINT REFERENCES users (id)
);

-- Starting values; the admin portal edits them.
INSERT INTO store_settings (store_id, delivery_fee, free_delivery_threshold, min_order_amount, online_payment_fee, eta_minutes)
VALUES (1, 15.00, 200.00, 50.00, 5.00, 20);

-- ---- orders --------------------------------------------------------------------------------

-- The number people see and say on the phone.
CREATE SEQUENCE order_number_seq START WITH 10001;

CREATE TABLE orders (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_number      BIGINT         NOT NULL DEFAULT nextval('order_number_seq'),
    user_id           BIGINT         NOT NULL REFERENCES users (id),
    store_id          BIGINT         NOT NULL REFERENCES stores (id),
    status            VARCHAR(20)    NOT NULL,
    payment_method    VARCHAR(10)    NOT NULL,
    -- Name, phone and address as they were when ordering; later profile changes never touch it.
    customer_snapshot JSONB          NOT NULL,
    address_id        BIGINT REFERENCES addresses (id),
    notes             VARCHAR(300),
    cash_change_for   NUMERIC(10, 2) CHECK (cash_change_for > 0),
    subtotal          NUMERIC(10, 2) NOT NULL CHECK (subtotal >= 0),
    delivery_fee      NUMERIC(10, 2) NOT NULL CHECK (delivery_fee >= 0),
    online_fee        NUMERIC(10, 2) NOT NULL CHECK (online_fee >= 0),
    discount          NUMERIC(10, 2) NOT NULL DEFAULT 0 CHECK (discount >= 0),
    total             NUMERIC(10, 2) NOT NULL CHECK (total >= 0),
    -- What the customer agreed to; admin edits may only lower the total.
    original_total    NUMERIC(10, 2) NOT NULL CHECK (original_total >= 0),
    items_changed     BOOLEAN        NOT NULL DEFAULT FALSE,
    eta_minutes       INT            NOT NULL,
    courier_name      VARCHAR(50),
    courier_phone     VARCHAR(13),
    cancel_reason     VARCHAR(300),
    cash_collected    BOOLEAN,
    idempotency_key   VARCHAR(64)    NOT NULL,
    version           INT            NOT NULL DEFAULT 0,
    created_at        TIMESTAMPTZ    NOT NULL DEFAULT now(),
    updated_at        TIMESTAMPTZ    NOT NULL DEFAULT now(),
    CONSTRAINT uq_orders_number UNIQUE (order_number),
    -- The same checkout attempt (key) by the same customer is one order, never two.
    CONSTRAINT uq_orders_idempotency UNIQUE (user_id, idempotency_key),
    CONSTRAINT ck_orders_status CHECK (status IN ('PENDING_REVIEW', 'CONFIRMED', 'OUT_FOR_DELIVERY', 'DELIVERED', 'CANCELLED')),
    CONSTRAINT ck_orders_payment CHECK (payment_method IN ('CASH', 'ONLINE')),
    CONSTRAINT ck_orders_total_not_raised CHECK (total <= original_total)
);

CREATE INDEX ix_orders_user_created ON orders (user_id, created_at DESC, id DESC);
CREATE INDEX ix_orders_store_status_created ON orders (store_id, status, created_at DESC);
CREATE INDEX ix_orders_snapshot_phone ON orders ((customer_snapshot ->> 'phone'));

CREATE TABLE order_items (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id            BIGINT         NOT NULL REFERENCES orders (id) ON DELETE CASCADE,
    product_id          BIGINT         NOT NULL REFERENCES products (id),
    -- Copied from the catalog at ordering time.
    name_ar             VARCHAR(100)   NOT NULL,
    name_en             VARCHAR(100)   NOT NULL,
    size_label          VARCHAR(40)    NOT NULL,
    image_hash          VARCHAR(12),
    unit_price          NUMERIC(10, 2) NOT NULL CHECK (unit_price >= 0),
    qty                 INT            NOT NULL CHECK (qty BETWEEN 0 AND 99),
    original_qty        INT            NOT NULL CHECK (original_qty BETWEEN 1 AND 99),
    substitution_pref   VARCHAR(10)    NOT NULL,
    line_status         VARCHAR(10)    NOT NULL DEFAULT 'OK',
    replaced_by_item_id BIGINT REFERENCES order_items (id),
    sort_order          INT            NOT NULL,
    CONSTRAINT ck_order_items_pref CHECK (substitution_pref IN ('REPLACE', 'REFUND', 'CALL_ME')),
    CONSTRAINT ck_order_items_status CHECK (line_status IN ('OK', 'REDUCED', 'REMOVED', 'REPLACED'))
);

CREATE INDEX ix_order_items_order ON order_items (order_id, sort_order);

-- Every status change (and every item edit), with who did it: the tracking timestamps and the audit trail.
CREATE TABLE order_events (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id   BIGINT       NOT NULL REFERENCES orders (id) ON DELETE CASCADE,
    kind       VARCHAR(20)  NOT NULL DEFAULT 'STATUS',
    status     VARCHAR(20)  NOT NULL,
    actor_type VARCHAR(10)  NOT NULL,
    actor_id   BIGINT,
    note       VARCHAR(300),
    at         TIMESTAMPTZ  NOT NULL,
    CONSTRAINT ck_order_events_kind CHECK (kind IN ('STATUS', 'ITEMS_EDITED')),
    CONSTRAINT ck_order_events_actor CHECK (actor_type IN ('CUSTOMER', 'ADMIN', 'SYSTEM'))
);

CREATE INDEX ix_order_events_order ON order_events (order_id, at, id);

-- ---- push devices --------------------------------------------------------------------------

CREATE TABLE user_devices (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    BIGINT       NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    fcm_token  VARCHAR(512) NOT NULL,
    platform   VARCHAR(10)  NOT NULL,
    updated_at TIMESTAMPTZ  NOT NULL,
    -- One phone, one owner: signing in as someone else moves the token.
    CONSTRAINT uq_user_devices_token UNIQUE (fcm_token),
    CONSTRAINT ck_user_devices_platform CHECK (platform IN ('ANDROID', 'IOS', 'WEB'))
);

CREATE INDEX ix_user_devices_user ON user_devices (user_id);
